const bytea = customType<{ data: Buffer }>({ dataType: () => "bytea" });

/**
 * An Organization's own CA (private-ca.ts): a root and the Issuing CAs under it (`issuing_ca`). With a platform-made root,
 * the root's key is in the KMS. The platform stores only certificates and the KMS's references to keys (ADR 0007).
 */
export const privateCa = pgTable(
  "private_ca",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id),
    name: text("name").notNull(),
    kind: text("kind").$type<PrivateCaKind>().notNull(),
    /** The root's status: a revoked root's Issuing CAs issue nothing. */
    status: text("status").$type<PrivateCaStatus>().notNull(),
    /** The algorithm of its keys, the root's and its Issuing CAs'. */
    keyAlgorithm: text("key_algorithm").$type<SigningKeyAlgorithm>().notNull(),
    /**
     * The root: its certificate (PEM), and for a platform-made one, the KMS's reference to its key. An Organization's own
     * root is uploaded with its first signed Issuing CA, with `chainPem`, the certificates between its Issuing CAs and it
     * (PEM, the one that signs them first; none when it signs them itself), which its Issuing CAs share.
     */
    rootCertificatePem: text("root_certificate_pem"),
    rootKey: text("root_key"),
    chainPem: text("chain_pem"),
    /**
     * The root's latest CRL, of its Issuing CAs (crl.ts): a full CRL signed by the root's key, kept as it was signed and served as it is, with its number
     * and when it is current from and until; none until it is first published. `crlFailingSince` is when its scheduled
     * reissue first failed since it was last published, none while publication works.
     */
    crlNumber: bigint("crl_number", { mode: "number" }),
    crlThisUpdate: timestamp("crl_this_update", { withTimezone: true }),
    crlNextUpdate: timestamp("crl_next_update", { withTimezone: true }),
    crlDer: bytea("crl_der"),
    crlFailingSince: timestamp("crl_failing_since", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    unique("private_ca_organization_name_unique").on(t.organizationId, t.name),
    // Lets other tables reference a Private CA together with its Organization, so none can point at another's.
    unique("private_ca_id_organization_unique").on(t.id, t.organizationId),
    check("private_ca_kind", sql`${t.kind} in ('platform_root', 'organization_root')`),
    check("private_ca_status", sql`${t.status} in ('active', 'revoked')`),
    check("private_ca_platform_root", sql`${t.kind} <> 'platform_root' or (${t.rootCertificatePem} is not null and ${t.rootKey} is not null)`),
  ],
);

/**
 * An Issuing CA of a Private CA: the CA whose key, in the KMS, signs Certificates. Each has its own subject (unique within
 * its Private CA), key, permitted name rules and validity limits; a platform-made one carries its rules as name constraints.
 */
export const issuingCa = pgTable(
  "issuing_ca",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: text("organization_id").notNull(),
    privateCaId: uuid("private_ca_id").notNull(),
    /** Its subject, as a distinguished name. */
    subject: text("subject").notNull(),
    /** Its certificate (PEM), once there is one, and the KMS's reference to its key. */
    certificatePem: text("certificate_pem"),
    key: text("key").notNull(),
    status: text("status").$type<IssuingCaStatus>().notNull(),
    /**
     * Its permitted name rules: the exact names, and the zones (each the name and everything beneath it), it may issue
     * for, normalised as Managed Certificates' names are. One made before there were rules has none, and issues for nothing.
     */
    permittedExactNames: text("permitted_exact_names").array().notNull().default(sql`'{}'`),
    permittedZones: text("permitted_zones").array().notNull().default(sql`'{}'`),
    /** The longest a TLS Certificate it issues may be valid for, in days, and how long one is when its Managed Certificate chooses no validity. */
    maxValidityDays: integer("max_validity_days").notNull().default(397),
    defaultValidityDays: integer("default_validity_days").notNull().default(397),
    /**
     * Its latest CRL, of the Certificates it signed (crl.ts): a full CRL signed by its key, kept as it was signed and served as it is, with its number
     * and when it is current from and until; none until it is first published. `crlFailingSince` is when its scheduled
     * reissue first failed since it was last published, none while publication works.
     */
    crlNumber: bigint("crl_number", { mode: "number" }),
    crlThisUpdate: timestamp("crl_this_update", { withTimezone: true }),
    crlNextUpdate: timestamp("crl_next_update", { withTimezone: true }),
    crlDer: bytea("crl_der"),
    crlFailingSince: timestamp("crl_failing_since", { withTimezone: true }),
    /** When it was revoked and why, which its root's CRL lists; none unless it is `revoked`. */
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
    revocationReason: text("revocation_reason").$type<RevocationReason>(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ columns: [t.privateCaId, t.organizationId], foreignColumns: [privateCa.id, privateCa.organizationId] }),
    unique("issuing_ca_private_ca_subject_unique").on(t.privateCaId, t.subject),
    // Lets other tables reference an Issuing CA together with its Organization, so none can point at another's.
    unique("issuing_ca_id_organization_unique").on(t.id, t.organizationId),
    check("issuing_ca_status", sql`${t.status} in ('awaiting_signature', 'active', 'retired', 'revoked')`),
    check("issuing_ca_signed", sql`${t.status} = 'awaiting_signature' or ${t.certificatePem} is not null`),
    check("issuing_ca_validity", sql`${t.defaultValidityDays} between 1 and ${t.maxValidityDays}`),
    check("issuing_ca_revoked", sql`(${t.status} = 'revoked') = (${t.revokedAt} is not null and ${t.revocationReason} is not null)`),
    check("issuing_ca_revocation_reason", sql`${t.revocationReason} in ('unspecified', 'keyCompromise', 'cACompromise', 'affiliationChanged', 'superseded', 'cessationOfOperation')`),
  ],
);

