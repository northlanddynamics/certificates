import { apiKey } from "@better-auth/api-key";
import { passkey } from "@better-auth/passkey";
import { betterAuth } from "better-auth";
import { admin, openAPI, organization, twoFactor } from "better-auth/plugins";
import type { OrganizationOptions } from "better-auth/plugins";
import { adminAc, userAc } from "better-auth/plugins/admin/access";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import type { NodePgDatabase } from "drizzle-orm/node-postgres";
import { ORG_ADMIN_ROLE, ac, orgRoles } from "./permissions";

export const INVITATION_EXPIRES_IN_SECONDS = 7 * 24 * 3600;

export const PLATFORM_OPERATOR_ROLE = "platform-operator";

/** How the platform names itself to authenticator apps and passkey managers. */
export const APP_NAME = "Certificate Platform";

/** The header an API key is sent in. */
export const API_KEY_HEADER = "x-api-key";

/** The plugin's configurations: a user's keys, and an Organization's. */
export const API_KEY_CONFIG = { user: "default", organization: "organization" } as const;

const API_KEY_OPTIONS = {
  apiKeyHeaders: API_KEY_HEADER,
  // A key's Organization (and, for an Organization's key, its maker) is in the metadata (see api-keys.ts).
  enableMetadata: true,
  requireName: true,
  // The plugin's default is 10 requests a day, far too few for a pipeline that fetches on every run.
  rateLimit: { enabled: true, timeWindow: 60 * 60 * 1000, maxRequests: 600 },
};

export interface AuthConfig {
  // Any Drizzle database; the adapter reads the schema from it (generated by the Better Auth CLI).
  db: NodePgDatabase<any>;
  baseURL: string;
  secret: string;
  /** Extra origins allowed to call the auth endpoints from a browser (e.g. the Vite dev server). */
  trustedOrigins?: string[];
  /** Hooks and mail for the organization plugin; set on the per-transaction instance (see organization-changes.ts). */
  organization?: Pick<OrganizationOptions, "organizationHooks" | "sendInvitationEmail">;
}

export function createAuth({ db, baseURL, secret, trustedOrigins = [], organization: orgExtras }: AuthConfig) {
  return betterAuth({
    database: drizzleAdapter(db, { provider: "pg" }),
    baseURL,
    secret,
    appName: APP_NAME,
    basePath: "/api/auth",
    trustedOrigins: [baseURL, ...trustedOrigins],
    // API keys are created, revoked and verified only through the platform's own routes (api-keys.ts), which scope a key
    // to an Organization and write its Audit Events with the change; none of the plugin's HTTP endpoints is served.
    disabledPaths: [
      "/api-key/create",
      "/api-key/verify",
      "/api-key/get",
      "/api-key/update",
      "/api-key/delete",
      "/api-key/list",
      "/api-key/delete-all-expired-api-keys",
    ],
    emailAndPassword: { enabled: true, autoSignIn: true, minPasswordLength: 12 },
    plugins: [
      // Documents Better Auth's own routes at /api/auth/open-api/generate-schema; the combined
      // reference page is served by the platform API at /api/docs (see app.ts).
      openAPI({ disableDefaultReference: true }),
      admin({
        adminRoles: [PLATFORM_OPERATOR_ROLE],
        defaultRole: "user",
        roles: { [PLATFORM_OPERATOR_ROLE]: adminAc, user: userAc },
      }),
      // TOTP as a second factor for password sign-in. Enrolling, verifying the first code and disabling are served on the
      // unit of work, which audits them (account-security.ts); the email/SMS OTP method is not configured.
      twoFactor({ issuer: APP_NAME }),
      // Passkeys sign in on their own, without a password or a second factor. The relying party is the host of `baseURL`,
      // and the expected origin is the request's, which Better Auth has already checked against `trustedOrigins`.
      passkey({ rpName: APP_NAME }),
      apiKey([
        // A user's keys: they belong to the person who made them (the plugin's default configuration).
        { ...API_KEY_OPTIONS, configId: API_KEY_CONFIG.user, references: "user", defaultPrefix: "cp_" },
        // An Organization's keys: they belong to the Organization and outlive whoever made them. Making, reading and
        // revoking them asks the organization plugin for the `apiKey` permissions (permissions.ts).
        { ...API_KEY_OPTIONS, configId: API_KEY_CONFIG.organization, references: "organization", defaultPrefix: "cpo_" },
      ]),
      organization({
        ac,
        roles: orgRoles,
        creatorRole: ORG_ADMIN_ROLE,
        ...orgExtras,
        // Our own Organizations stay far below these; Better Auth's defaults are 100 members and 100 pending invitations.
        membershipLimit: 10_000,
        invitationLimit: 10_000,
        invitationExpiresIn: INVITATION_EXPIRES_IN_SECONDS,
        // Deleting an Organization is not a thing the platform offers, and its data (audit log) must outlive it.
        disableOrganizationDeletion: true,
        // requireEmailVerificationOnInvitation stays off until sign-up verifies email (see ticket 28).
        teams: {
          enabled: true,
          // Better Auth refuses to delete an Organization's last Team by default.
          allowRemovingAllTeams: true,
        },
        // Organizations are created only by Platform Operators, through the platform API.
        allowUserToCreateOrganization: false,
      }),
    ],
  });
}

export type Auth = ReturnType<typeof createAuth>;
