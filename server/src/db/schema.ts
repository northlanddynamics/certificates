/**
 * One attempt to obtain a Certificate for a Managed Certificate: it runs while the platform does DCV and finalizes the
 * order, and ends in a Certificate or in the cause of its failure. At most one runs at a time for a Managed Certificate.
 */
export const issuance = pgTable(
  "issuance",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id),
    managedCertificateId: uuid("managed_certificate_id").notNull(),
    status: text("status").$type<"running" | "succeeded" | "failed">().notNull(),
    /** Who asked for it; the Audit Events of its outcome are attributed to them. None when the Renewal scheduler did. */
    requestedById: text("requested_by_id"),
    requestedByEmail: text("requested_by_email"),
    failureCode: text("failure_code").$type<IssuanceFailureCode>(),
    failureMessage: text("failure_message"),
    certificateId: uuid("certificate_id"),
    startedAt: timestamp("started_at", { withTimezone: true }).notNull(),
    finishedAt: timestamp("finished_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ columns: [t.managedCertificateId, t.organizationId], foreignColumns: [managedCertificate.id, managedCertificate.organizationId] }),
    index("issuance_managed_certificate_idx").on(t.managedCertificateId, t.createdAt),
    uniqueIndex("issuance_one_running_per_managed_certificate")
      .on(t.managedCertificateId)
      .where(sql`${t.status} = 'running'`),
  ],
);

/**
 * One issued X.509 certificate, identified by its fingerprint. Immutable: a trigger (see the
 * certificate_immutable migration) rejects UPDATE and DELETE.
 */
export const certificate = pgTable(
  "certificate",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id),
    managedCertificateId: uuid("managed_certificate_id").notNull(),
    /** SHA-256 of the leaf's DER, lower-case hex. */
    fingerprint: text("fingerprint").notNull(),
    /** The leaf's serial number, upper-case hex. */
    serial: text("serial").notNull(),
    notBefore: timestamp("not_before", { withTimezone: true }).notNull(),
    notAfter: timestamp("not_after", { withTimezone: true }).notNull(),
    /** The names the leaf covers (its subject alternative names), lower case. */
    names: text("names").array().notNull(),
    /** The leaf followed by the intermediates the CA served, PEM. */
    chainPem: text("chain_pem").notNull(),
    /** The CA it came from (its name in the Certificate Authority interface), and the ACME account used there. */
    ca: text("ca").notNull(),
    environment: text("environment").$type<AcmeEnvironment>().notNull(),
    acmeAccountId: uuid("acme_account_id")
      .notNull()
      .references(() => acmeAccount.id),
    issuedAt: timestamp("issued_at", { withTimezone: true }).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    unique("certificate_organization_fingerprint_unique").on(t.organizationId, t.fingerprint),
    index("certificate_managed_certificate_idx").on(t.managedCertificateId, t.createdAt),
    foreignKey({ columns: [t.managedCertificateId, t.organizationId], foreignColumns: [managedCertificate.id, managedCertificate.organizationId] }),
  ],
);

/**
 * What the CA's ACME Renewal Information last said about a Certificate, and when to ask again. The Certificate stays as
 * it was issued; this is what the scheduler has learned about it since. No window means the CA offered none.
 */
export const renewalInfo = pgTable(
  "renewal_info",
  {
    certificateId: uuid("certificate_id")
      .primaryKey()
      .references(() => certificate.id),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id),
    windowStart: timestamp("window_start", { withTimezone: true }),
    windowEnd: timestamp("window_end", { withTimezone: true }),
    /** When the CA last answered; none if it never has. */
    checkedAt: timestamp("checked_at", { withTimezone: true }),
    /** Not asked again before this: the CA's Retry-After, or a wait the platform chose. */
    nextCheckAt: timestamp("next_check_at", { withTimezone: true }).notNull(),
  },
  (t) => [check("renewal_info_window", sql`(${t.windowStart} is null) = (${t.windowEnd} is null)`)],
);
