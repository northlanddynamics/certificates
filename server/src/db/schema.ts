const bytea = customType<{ data: Buffer }>({ dataType: () => "bytea" });

/** Every domain table carries organization_id and every query filters by it. */
export const managedCertificate = pgTable(
  "managed_certificate",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id),
    /** The names to issue, lower case, wildcards as `*.example.com`; in the order the creator gave them. */
    names: text("names").array().notNull(),
    keyAlgorithm: text("key_algorithm").$type<KeyAlgorithm>().notNull(),
    keyCustody: text("key_custody").$type<KeyCustody>().notNull(),
    /** Which of the Organization's ACME accounts, by environment, Certificates are obtained through. */
    environment: text("environment").$type<AcmeEnvironment>().notNull(),
    /** The CSR under which Certificates are issued (Key Custody: Owner), so Renewal can reuse it. */
    csr: text("csr").notNull(),
    /** Whether its names have the Approval they need: `not_required` when an Organization Administrator created it. */
    approvalStatus: text("approval_status").$type<ApprovalStatus>().notNull().default("not_required"),
    /** Who proposed it, when someone who needs Approval did; null for one that never needed it. */
    proposedById: text("proposed_by_id"),
    proposedByEmail: text("proposed_by_email"),
    decidedById: text("decided_by_id"),
    decidedByEmail: text("decided_by_email"),
    decidedAt: timestamp("decided_at", { withTimezone: true }),
    /** What the Approver said; required for a rejection, optional for an approval. */
    decisionReason: text("decision_reason"),
    /** Whether the scheduler renews it, or only a person does (its Renewal Policy), and how many days before its Certificate ends it is due. */
    renewalMode: text("renewal_mode").$type<RenewalMode>().notNull().default("automatic"),
    renewalDaysBeforeExpiry: integer("renewal_days_before_expiry").notNull().default(30),
    /** When it was archived: it is hidden from the inventory unless archived ones are asked for. Null while it is live. */
    archivedAt: timestamp("archived_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("managed_certificate_org_idx").on(t.organizationId),
    check("managed_certificate_renewal_mode", sql`${t.renewalMode} in ('automatic', 'manual')`),
    check("managed_certificate_renewal_days", sql`${t.renewalDaysBeforeExpiry} between 1 and 365`),
    // Lets other tables reference a Managed Certificate together with its Organization, so none can point at another's.
    unique("managed_certificate_id_organization_unique").on(t.id, t.organizationId),
  ],
);

/**
 * A change of a Managed Certificate's names, with the CSR for the new names. One by a non-administrator waits for
 * Approval (`pending`) while Renewal carries on with the Managed Certificate's own names and CSR, which the change
 * replaces only when approved. One that is rejected, withdrawn by its proposer or discarded by the platform (its proposer
 * left the Organization, or its Managed Certificate was archived) is kept as a record and changes nothing. An Organization
 * Administrator's change is applied as it is made and leaves only its Audit Event. At most one is pending for a Managed Certificate.
 */
export const nameChange = pgTable(
  "name_change",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id),
    managedCertificateId: uuid("managed_certificate_id").notNull(),
    status: text("status").$type<NameChangeStatus>().notNull(),
    /** The names asked for; lower case. */
    names: text("names").array().notNull(),
    /** The CSR for `names`, which replaces the Managed Certificate's when the change is approved. */
    csr: text("csr").notNull(),
    proposedById: text("proposed_by_id").notNull(),
    proposedByEmail: text("proposed_by_email").notNull(),
    /** Who ended it, when and why it ended: an Approver's decision, the proposer's withdrawal, or what made the platform discard it (none, then). */
    decidedById: text("decided_by_id"),
    decidedByEmail: text("decided_by_email"),
    decidedAt: timestamp("decided_at", { withTimezone: true }),
    decisionReason: text("decision_reason"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ columns: [t.managedCertificateId, t.organizationId], foreignColumns: [managedCertificate.id, managedCertificate.organizationId] }),
    index("name_change_managed_certificate_idx").on(t.managedCertificateId, t.createdAt),
    index("name_change_pending_idx").on(t.organizationId).where(sql`${t.status} = 'pending'`),
    uniqueIndex("name_change_one_pending_per_managed_certificate")
      .on(t.managedCertificateId)
      .where(sql`${t.status} = 'pending'`),
    check("name_change_status", sql`${t.status} in ('pending', 'approved', 'rejected', 'withdrawn', 'discarded')`),
  ],
);

/**
 * A user or a Team accountable for a Managed Certificate: exactly one of `userId` and `teamId`. A Managed Certificate
 * may have none. Owners see the Managed Certificate (visibility) and may change who its Owners are. A user must be a
 * member of the Organization and a Team one of its Teams; the platform checks that when adding, and takes an Owner off
 * when its user leaves the Organization or its Team is deleted.
 */
export const managedCertificateOwner = pgTable(
  "managed_certificate_owner",
  {
    /** Rising, so Owners are listed in the order they were added. */
    id: bigint("id", { mode: "number" }).primaryKey().generatedAlwaysAsIdentity(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id),
    managedCertificateId: uuid("managed_certificate_id").notNull(),
    userId: text("user_id").references(() => user.id, { onDelete: "cascade" }),
    teamId: text("team_id").references(() => team.id, { onDelete: "cascade" }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ columns: [t.managedCertificateId, t.organizationId], foreignColumns: [managedCertificate.id, managedCertificate.organizationId] }),
    check("managed_certificate_owner_user_xor_team", sql`(${t.userId} is null) <> (${t.teamId} is null)`),
    uniqueIndex("managed_certificate_owner_user_unique").on(t.managedCertificateId, t.userId).where(sql`${t.userId} is not null`),
    uniqueIndex("managed_certificate_owner_team_unique").on(t.managedCertificateId, t.teamId).where(sql`${t.teamId} is not null`),
    index("managed_certificate_owner_user_idx").on(t.organizationId, t.userId),
    index("managed_certificate_owner_team_idx").on(t.organizationId, t.teamId),
  ],
);

